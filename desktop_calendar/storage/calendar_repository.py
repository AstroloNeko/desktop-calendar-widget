"""Storage contract: detached reads and one prepared business change set.

Record values retain the existing model types. JSON tokens are session-local;
SQLite tokens carry a persistent calendar ID/revision. Neither is an object-level
revision. Backend guarantees must not be inferred from the shared token shape.
"""
from dataclasses import dataclass
from typing import Protocol, Mapping, Any


class RepositoryConflictError(ValueError):
    pass


@dataclass(frozen=True)
class SnapshotToken:
    session: str
    generation: int


@dataclass(frozen=True)
class RepositoryCommit:
    changed: bool
    revision: SnapshotToken
    operation_id: str | None = None
    replayed: bool = False


class CalendarRepository(Protocol):
    def get_event(self, identifier): ...
    def list_events(self): ...
    def get_routine(self, identifier): ...
    def list_routines(self): ...
    def get_category(self, identifier): ...
    def list_categories(self): ...
    def get_date_states(self): ...
    def read_preferences(self): ...
    def read_calendar_snapshot(self): ...
    def revision(self) -> SnapshotToken: ...
    def invalidate_snapshots(self): ...
    def apply_changes(self, changes: Mapping[str, Any], *, expected_revision=None, preference_updates=None) -> RepositoryCommit: ...

    # Transitional Store integration. Backend owns I/O; Store owns normalization.
    def read_document(self): ...
    def write_current(self): ...
    def close(self): ...
